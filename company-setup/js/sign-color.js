// 글 속 +/− 숫자에 오르내림 색 — 오름 빨강 · 내림 파랑(num-up · num-dn · 시황분석 탭 국내 시장 칸 · 홈 칩과 같은 색) (2026-10-14 재권님
// 「여기에도 숫자에 색이 있으면 좋을거같아」 · 「시황분석에 있는 숫자들 들어가는게 합리적인건 다 적용해주면 좋겠어」 · 시황분석1). 셈은 이 한 곳.
//   · 부호가 숫자에 바로 붙은 것만 칠한다 — 「+2.8%」 · 「-14bp」 · 「-2조 103억원」. 띄운 빼기(「10년 − 2년」) · 날짜(2026-10-13) · 부호 없는 수는 안 칠한다
//   · 받는 것은 이미 만든 HTML — 태그 안 글자는 건드리지 않는다
const NUM = /(^|[\s(·,:→/~])([+\-−])(\d[\d,]*(?:\.\d+)?(?:%p|%|bp|조(?:\s\d[\d,]*억원?)?|억원|억|원|배|p)?)/g;
export const signColor = html => String(html).split(/(<[^>]+>)/).map(part => part.startsWith('<') ? part
  : part.replace(NUM, (m, pre, sg, n) => `${pre}<span class="${sg === '+' ? 'num-up' : 'num-dn'}">${sg}${n}</span>`)).join('');
