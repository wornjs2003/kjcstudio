/* ==========================================================================
   아직 연결하지 않은 자리

   화면에 예시 데이터를 채워 두면 실제 값처럼 보여서, 연결이 안 된 건지
   원래 그런 값인지 구분할 수 없다. 그래서 받아올 곳이 없는 자리에는
   숫자 대신 이 안내를 둔다. 나중에 무엇을 붙여야 하는지도 함께 적는다.
   ========================================================================== */

/**
 * @param {string} what  무엇이 비어 있는지 (예: '뉴스·공시')
 * @param {string} todo  무엇을 붙이면 채워지는지 (예: 'DART 공시 API')
 */
export function notConnected(what, todo) {
  return `
    <div class="kh-empty">
      <div class="kh-empty-title">${what} — 아직 연결하지 않았습니다</div>
      <div class="kh-empty-todo">붙일 것: ${todo}</div>
    </div>
  `;
}
