# 이름에 쓸 수 있는 글자만 받는다. 넓게 잡으면 대화에 섞인 코드 조각까지
# 이름으로 잡히는 일이 생긴다 (실제로 그랬다).
RENAME = re.compile(r"Session renamed to: ([가-힣A-Za-z0-9_\-. ]{1,30})")


def find_name(path):
    """마지막 rename 기록을 찾는다. 기록 줄의 **종류까지** 본다.

    전에는 파일 전체를 글자로 훑어 마지막 매치를 썼다. 그러다 세션 하나가
    **남의 이름을 달았다.** 2026-09-16 에 `작업우선순위` 세션이 목록에
    `홈페이지_정리` 로 올라왔다. 그 세션 기록을 세어보니 이랬다.

        '작업우선순위'   1회   ← 진짜 자기 이름
        '홈페이지_정리'   2회   ← 남의 기록을 읽다가 들어온 것

    그 세션은 **다른 세션의 기록을 읽는 것이 일**이라, 읽은 내용이 자기
    대화에 남는다. 글자만 보면 남 얘기와 자기 이름을 구분할 수 없다.

    진짜 rename 은 이렇게 생겼다.

        {"type":"system","subtype":"local_command",
         "content":"<local-command-stdout>Session renamed to: 개념정의</...>"}

    읽다가 들어온 것은 `"type":"tool_use"` 안의 명령 문자열이다.
    그래서 **`type` 이 `system` 인 줄만** 인정한다.

    예전에 이름이 `([^` 로 잡혔던 것도 같은 뿌리였다. 그때는 정규식을
    좁혀 막았는데, 이름 규칙에 맞는 남의 이름은 그것으로 못 거른다.
    """
    name = ""
    try:
        with io.open(path, encoding="utf-8", errors="ignore") as fp:
            for line in fp:
                if "Session renamed to:" not in line:
                    continue
                try:
                    row = json.loads(line)
                except ValueError:
                    continue          # 잘린 줄은 버린다
                if row.get("type") != "system":
                    continue          # 대화에 섞여 들어온 남의 기록
                m = RENAME.search(str(row.get("content", "")))
                if m:
                    name = m.group(1).strip()
    except OSError:
        pass
    return name


def collect():
    rows = []
    if not os.path.isdir(LOGS):
        return rows
    for fn in os.listdir(LOGS):
        if not fn.endswith(".jsonl"):
            continue
        path = os.path.join(LOGS, fn)
        name = find_name(path)
        if not name:                      # 이름 없는 세션은 싣지 않는다
            continue
        rows.append({
            "id": fn[:-6],
            "name": name,
            "mtime": datetime.fromtimestamp(os.path.getmtime(path)),
            "mb": os.path.getsize(path) / 1024 / 1024,
        })
    rows.sort(key=lambda r: r["mtime"], reverse=True)
    return rows


def write_bat(rows):
    """세션 창을 여는 배치 파일. 목록도 한글도 여기 적지 않는다.

    두 가지를 일부러 뺐다.

    **세션 목록** — 전에는 세션마다 `start` 줄을 박아 넣었는데, 이 스크립트가
    실행 도중 이 파일을 다시 쓰기 때문에 cmd 가 읽던 위치를 잃고 마지막 줄을
    건너뛰었다. 지금은 파이썬을 부르는 한 줄만 두고, 창 여는 일은 파이썬이 맡는다.

    **한글** — `chcp 65001` 로 코드페이지를 바꾸면 cmd 가 배치 파일의 바이트를
    세는 방식이 달라진다. cmd 는 한 줄 실행할 때마다 파일을 다시 열어 바이트
    위치로 되짚으므로, 아래쪽에 한글이 있으면 위치가 어긋나 줄 중간부터
    실행된다. 실제로 startup.bat 에서 `'/*' 은 명령이 아닙니다` 같은 조각이
    쏟아졌다. 한글 메시지는 파이썬이 출력한다.
    """
    lines = [
        "@echo off",
        "chcp 65001 > nul",
        "REM ===================================================================",
        "REM  KJC Studio - reopen every named Claude session",
        "REM",
        "REM  Generated by tools/update-sessions.py. Do not edit by hand.",
        "REM  A session joins this list once it has been given a name",
        "REM  with /rename - nothing here needs changing.",
        "REM",
        "REM  KEEP THIS FILE ASCII-ONLY. After `chcp 65001` cmd miscounts the",
        "REM  bytes of its own batch file, so Korean text below makes it lose",
        "REM  its place mid-line. The Korean output comes from Python.",
        "REM ===================================================================",
        "",
        'cd /d "%~dp0"',
        "",
        "REM Rescan the list, then open each session that is not already up.",
        "python tools\\update-sessions.py --open",
        "",
        "ping -n 3 127.0.0.1 > nul",
    ]
    # .bat 은 CRLF 로 저장한다 (.gitattributes 규칙)
    with io.open(BAT, "w", encoding="utf-8", newline="\r\n") as fp:
        fp.write("\n".join(lines) + "\n")


