def running_ids():
    """`--resume` 으로 이미 열려 있는 세션 id 를 모은다.

    같은 세션을 두 창에서 열면 한쪽 기록이 꼬인다. 실행할 때마다 확인해서
    떠 있는 것은 건너뛴다. 덕분에 재부팅 뒤가 아니어도 안심하고 돌릴 수 있다.

    `--resume` 없이 연 창(`claude --continue` 등)은 여기 안 잡힌다.
    이 스크립트가 여는 것은 전부 `--resume` 이므로 중복을 막기에는 충분하다.
    """
    import subprocess
    try:
        out = subprocess.run(
            ["powershell", "-NoProfile", "-Command",
             "Get-CimInstance Win32_Process | "
             "Where-Object { $_.CommandLine -match 'resume' } | "
             "ForEach-Object { $_.CommandLine }"],
            capture_output=True, text=True, timeout=25,
        ).stdout or ""
    except Exception:
        return set()
    return set(re.findall(r"resume\s+([0-9a-f-]{36})", out))


def open_windows(rows):
    """세션마다 새 콘솔 창을 띄운다. 이미 열려 있는 것은 건너뛴다.

    배치 파일이 `start` 로 직접 열지 않고 여기서 여는 이유가 있다.
    resume-sessions.bat 은 실행 도중 이 스크립트를 불러 **자기 자신을 다시 쓴다**.
    cmd 는 배치 파일을 한 줄씩 읽어가며 실행하므로, 읽는 중에 파일이 바뀌면
    읽던 위치가 어긋나 남은 줄을 건너뛴다. 창을 여는 일을 파이썬으로 옮겨
    그 구조 자체를 없앴다.
    """
    import subprocess
    live = running_ids()
    opened = skipped = 0
    for r in rows:
        if r["id"] in live:
            print(f"  건너뜀 {r['name']} — 이미 열려 있음")
            skipped += 1
            continue
        # `start` 를 쓰지 않는다. 창 제목을 첫 인자로 넘겼는데, `start` 는
        # **따옴표가 붙어 있을 때만** 그것을 제목으로 본다. 세션 이름에는
        # 공백이 없어서 subprocess 가 따옴표를 안 붙였고, 그래서 `start` 가
        # 이름을 실행 대상으로 읽었다 (2026-09-16).
        #
        #     열기   홈페이지_정리
        #     파일 홈페이지_정리을(를) 찾을 수 없습니다.
        #
        # 창은 뜨지 않았는데 「열었습니다」 로 셌다. 전에는 네 세션이 전부
        # 이미 떠 있어 이 줄을 지나갈 일이 없었던 터라 드러나지 않았다.
        # `startup.bat` 이 부르는 자리이므로 재부팅 때마다 지나간다.
        #
        # CREATE_NEW_CONSOLE 이면 `start` 없이 바로 새 콘솔이 열린다.
        # 제목은 cmd 의 `title` 로 단다.
        subprocess.Popen(
            ["cmd", "/k", f'title {r["name"]} && cd /d "{REPO}" && claude --resume {r["id"]}'],
            creationflags=subprocess.CREATE_NEW_CONSOLE,
        )
        print(f"  열기   {r['name']}")
        opened += 1
    print(f"\n  {opened}개 열었습니다" + (f" · {skipped}개는 이미 떠 있어 건너뛰었습니다" if skipped else ""))


def main():
    quiet = "--quiet" in sys.argv
    rows = collect()
    write_bat(rows)
    write_doc(rows)

    if "--open" in sys.argv:
        if not rows:
            print("이름이 붙은 세션이 없습니다. 각 창에서 /rename 을 먼저 쓰세요.")
            return
        print(f"세션 {len(rows)}개를 엽니다.")
        open_windows(rows)
        return

    if not quiet:
        print(f"세션 {len(rows)}개를 찾았습니다.")
        for r in rows:
            print(f"  {r['name']:<16} {r['id']}  ({r['mtime']:%m-%d %H:%M})")
        print()
        print(f"  {BAT}")
        print(f"  {DOC}")


if __name__ == "__main__":
    main()
